const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const script = fs.readFileSync('resources/mcp/apps/revenue-dashboard-v1.html','utf8').match(/<script>([\s\S]*?)<\/script>/)[1];
const elements = new Map();
const get = id => { if (!elements.has(id)) elements.set(id, {innerHTML:'',textContent:'',hidden:false}); return elements.get(id); };
const context = vm.createContext({Intl, document:{getElementById:get}, window:{addEventListener(){}}, console});
vm.runInContext(script, context);
const metric = value => ({normalized_total:value,normalized_currency:'USD',payments_count:1});
const payload = {data:{summary:{window:{from:'2026-11-12T17:00:00Z',to:'2026-11-13T02:09:00Z'},metrics:{collected_revenue:{value:metric(30)}},visitor_revenue:metric(10),collections:{new_cash:metric(null),wallet_redemptions:metric(20)}},trend:{bucket:'hour',points:[{label:'2026-11-12T20:00:00+03:00',value:null,normalized_currency:'USD'}]},market_breakdown:{total:null,markets:[{platform_label:'Uganda English',country:'Uganda',value:null,normalized_total:null,normalized_currency:'USD',payments_count:1}]}},meta:{result_state:'partial',caveats:['Cached FX unavailable']}};
context.fixture = payload;
vm.runInContext('render(fixture)',context);
assert.match(get('metrics').innerHTML,/New cash · all services/);
assert.match(get('metrics').innerHTML,/Unavailable/);
assert.match(get('metrics').innerHTML,/Subscription service value/);
assert.doesNotMatch(get('metrics').innerHTML,/>Active</);
assert.match(get('trend').innerHTML,/Unavailable/);
assert.equal(get('marketTotal').textContent,'Unavailable');
assert.match(get('markets').innerHTML,/Uganda English/);
assert.match(get('markets').innerHTML,/Unavailable/);
assert.equal(get('caveats').hidden,false);
assert.equal(get('state').textContent,'partial');
context.fixture = {data:{summary:{metrics:{collected_revenue:{label:'Collected Revenue',value:metric(50)}}},trend:{},market_breakdown:{}},meta:{}};
vm.runInContext('render(fixture)',context);
assert.match(get('metrics').innerHTML,/Collected Revenue/);
assert.match(get('metrics').innerHTML,/\$50.00/);
assert.doesNotMatch(get('metrics').innerHTML,/New cash · all services/);
console.log('MCP revenue app contract: 13 assertions PASS');
